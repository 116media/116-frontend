/**
 * Pointer travel (px) beyond which a gesture is treated as a swipe, not a tap.
 */
export const TAP_MOVE_TOLERANCE = 10;

/**
 * Continuous active-playback time (ms) a short must accrue before a view event
 * fires — the engagement gate.
 */
export const VIEW_ENGAGEMENT_MS = 2000;

/**
 * Duration (ms) the double-tap heart burst stays on screen before it clears.
 */
export const LIKE_BURST_MS = 600;
